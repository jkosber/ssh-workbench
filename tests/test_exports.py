"""Workbench's own SSH config file and the one Include line; temporary folders only."""

import os
from pathlib import Path

import pytest

from ssh_workbench.config import Machine
from ssh_workbench.exports import (
    EXPORT_NAME,
    INCLUDE_LINE,
    ExportError,
    add_include,
    format_exports,
    include_present,
    write_exports,
)

BOX = Machine(
    "box",
    "Box",
    user="dev",
    addresses=("192.0.2.60", "box.example"),
    port=2222,
    key="C:\\Fictional Keys\\100%\\id_box",
    export_alias=True,
)
PLAIN = Machine("plain", "Plain", addresses=("192.0.2.61",), export_alias=True)
HOME_KEY = Machine(
    "home", "Home", addresses=("192.0.2.63",), key="~\\.ssh\\id_home", export_alias=True
)
QUIET = Machine("quiet", "Quiet", addresses=("192.0.2.62",))
GARDEN = Machine("garden", "Garden", alias="garden-host")
HEADER = (
    "# Generated by SSH Workbench from its machine file; edits here are overwritten.\n"
    "# Your SSH config includes it with: Include ssh-workbench.config\n"
)


def test_names() -> None:
    assert (EXPORT_NAME, INCLUDE_LINE) == (
        "ssh-workbench.config",
        "Include ssh-workbench.config",
    )


def test_exported_machines_become_host_blocks() -> None:
    assert format_exports([BOX, QUIET, GARDEN, PLAIN, HOME_KEY]) == HEADER + (
        "\n"
        "Host box\n"
        "    HostName 192.0.2.60\n"
        "    User dev\n"
        "    Port 2222\n"
        "    HostKeyAlias box\n"
        '    IdentityFile "C:/Fictional Keys/100%%/id_box"\n'
        "    IdentitiesOnly yes\n"
        "\n"
        "Host plain\n"
        "    HostName 192.0.2.61\n"
        "    HostKeyAlias plain\n"
        "\n"
        "Host home\n"
        "    HostName 192.0.2.63\n"
        "    HostKeyAlias home\n"
        '    IdentityFile "~/.ssh/id_home"\n'
        "    IdentitiesOnly yes\n"
    )
    assert format_exports([QUIET, GARDEN]) == HEADER


@pytest.mark.parametrize("key", ['C:\\Keys\\a"b', "C:\\Keys\\a\nb", "C:\\Keys\\a\tb"])
def test_a_key_path_that_cannot_be_written_is_refused(key: str) -> None:
    machine = Machine(
        "box", "Box", addresses=("192.0.2.60",), key=key, export_alias=True
    )

    with pytest.raises(ExportError) as caught:
        format_exports([machine])

    assert str(caught.value) == (
        "Can't export box: its key path can't be written to an SSH config."
    )


def test_the_file_is_written_only_once_something_is_exported(tmp_path: Path) -> None:
    folder = tmp_path / "ssh"
    exported = folder / EXPORT_NAME

    write_exports(folder, [QUIET, GARDEN])
    assert not folder.exists()

    write_exports(folder, [PLAIN, QUIET])
    assert exported.read_text(encoding="utf-8") == format_exports([PLAIN])
    if os.name == "posix":
        assert exported.stat().st_mode & 0o777 == 0o600

    write_exports(folder, [QUIET])
    assert exported.read_text(encoding="utf-8") == HEADER
    assert sorted(item.name for item in folder.iterdir()) == [EXPORT_NAME]


@pytest.mark.parametrize(
    ("text", "present"),
    [
        ("", False),
        ("Include ssh-workbench.config\nHost a\n", True),
        ("include=ssh-workbench.config\n", True),
        ("  INCLUDE ~/.ssh/ssh-workbench.config other.conf\n", True),
        ('Include "ssh-workbench.config"\n', True),
        ("# Include ssh-workbench.config\nHost a\n", False),
        ("Host a\nInclude ssh-workbench.config\n", False),
        ("Match host a\nInclude ssh-workbench.config\n", False),
        ("Include other.config\n", False),
        ("Include ssh-workbench.config.bak\n", False),
    ],
)
def test_include_present(text: str, present: bool) -> None:
    assert include_present(text) is present


def test_a_missing_config_is_created_with_the_line(tmp_path: Path) -> None:
    config = tmp_path / "config"

    add_include(config)

    assert config.read_bytes() == b"Include ssh-workbench.config\n"
    assert not (tmp_path / "config.ssh-workbench.bak").exists()
    if os.name == "posix":
        assert config.stat().st_mode & 0o777 == 0o600


@pytest.mark.parametrize(
    ("original", "expected"),
    [
        (
            b"Host a\n    HostName 192.0.2.1\n",
            b"Include ssh-workbench.config\nHost a\n    HostName 192.0.2.1\n",
        ),
        (
            b"Host a\r\n    User x\r\n",
            b"Include ssh-workbench.config\r\nHost a\r\n    User x\r\n",
        ),
        (
            b"\xef\xbb\xbfHost a\n",
            b"\xef\xbb\xbfInclude ssh-workbench.config\nHost a\n",
        ),
        (b"Host a", b"Include ssh-workbench.config\nHost a"),
        (b"", b"Include ssh-workbench.config\n"),
    ],
)
def test_the_line_is_added_and_every_other_byte_kept(
    tmp_path: Path, original: bytes, expected: bytes
) -> None:
    config = tmp_path / "config"
    config.write_bytes(original)
    if os.name == "posix":
        config.chmod(0o600)

    add_include(config)

    assert config.read_bytes() == expected
    assert (tmp_path / "config.ssh-workbench.bak").read_bytes() == original
    if os.name == "posix":
        assert config.stat().st_mode & 0o777 == 0o600
