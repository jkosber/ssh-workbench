"""Workbench's own SSH config file for exported machines, and its one Include line.

Workbench writes `ssh-workbench.config` in the SSH folder and, only after the
user says yes, inserts one `Include` line at the top of the user's SSH config.
It never changes any other line of that config.
"""

import os
import re
from collections.abc import Sequence
from pathlib import Path

from ssh_workbench.config import Machine
from ssh_workbench.store import replace_atomically

EXPORT_NAME = "ssh-workbench.config"
INCLUDE_LINE = f"Include {EXPORT_NAME}"
BACKUP_NAME = "config.ssh-workbench.bak"
_SOURCE = "# Machine file: "
_BOM = b"\xef\xbb\xbf"
_KEYWORD = re.compile(r"\s*([A-Za-z]+)(?:\s*=\s*|\s+)(.*)")
_WORD = re.compile(r'"([^"]*)"|(\S+)')


class ExportError(Exception):
    """An export could not be written; the message is safe to display."""


def format_exports(machines: Sequence[Machine], source: Path) -> str:
    """One `Host <id>` block per exported direct machine, after the header.

    The header names the machine file the blocks come from.
    """
    if any(ord(c) < 32 or ord(c) == 127 for c in str(source)):
        raise ExportError(
            "Can't export: the machine file's path can't be written to an SSH config."
        )
    blocks = [
        "# Generated by SSH Workbench from its machine file; edits here are "
        "overwritten.\n"
        f"{_SOURCE}{source}\n"
        f"# Your SSH config includes it with: {INCLUDE_LINE}\n"
    ]
    for machine in machines:
        if not machine.export_alias or machine.alias is not None:
            continue
        lines = [f"Host {machine.id}", f"    HostName {machine.addresses[0]}"]
        if machine.user is not None:
            lines.append(f"    User {machine.user}")
        if machine.port is not None:
            lines.append(f"    Port {machine.port}")
        # The same host-key entry as Connect, whichever address SSH reaches.
        lines.append(f"    HostKeyAlias {machine.id}")
        if machine.key is not None:
            lines.append(f'    IdentityFile "{_key_value(machine)}"')
            lines.append("    IdentitiesOnly yes")
        blocks.append("\n" + "\n".join(lines) + "\n")
    return "".join(blocks)


def _key_value(machine: Machine) -> str:
    key = machine.key or ""
    if any(c == '"' or ord(c) < 32 or ord(c) == 127 for c in key):
        raise ExportError(
            f"Can't export {machine.id}: its key path can't be written to an SSH "
            "config."
        )
    # OpenSSH reads `/` on every platform and expands `%` tokens in IdentityFile.
    return key.replace("\\", "/").replace("%", "%%")


def write_exports(folder: Path, machines: Sequence[Machine], source: Path) -> None:
    """Rewrite the generated file from `source`'s machines.

    It is created only once something is exported, and left alone when another
    machine file wrote it: one SSH folder serves every machine file.
    """
    path = folder / EXPORT_NAME
    exported = any(machine.export_alias for machine in machines)
    try:
        owner = _owner(path)
    except OSError as error:
        raise ExportError(f"Could not write {EXPORT_NAME}: {_reason(error)}.") from None
    if owner is not None and not _same_file(owner, source):
        if exported:
            raise ExportError(
                f"{EXPORT_NAME} holds the exports of {owner}; this machine file's "
                "exports were not written."
            )
        return
    if not exported and not path.exists():
        return
    text = format_exports(machines, source)
    try:
        folder.mkdir(mode=0o700, parents=True, exist_ok=True)
        replace_atomically(path, text.encode("utf-8"), mode_from=None)
        if os.name == "posix":
            # SSH refuses a config file that others may write.
            path.chmod(0o600)
    except OSError as error:
        raise ExportError(f"Could not write {EXPORT_NAME}: {_reason(error)}.") from None


def _owner(path: Path) -> str | None:
    """The machine file named in an existing generated file, if any."""
    if not path.exists():
        return None
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith(_SOURCE):
            return line.removeprefix(_SOURCE)
    return None


def _same_file(owner: str, source: Path) -> bool:
    return os.path.normcase(os.path.abspath(owner)) == os.path.normcase(
        os.path.abspath(source)
    )


def include_present(text: str) -> bool:
    """Whether an `Include` of the generated file comes before any Host or Match."""
    # Windows PowerShell 5.1 writes files that start with a byte-order mark.
    for line in text.removeprefix(chr(0xFEFF)).splitlines():
        match = _KEYWORD.match(line)
        if match is None:
            continue
        keyword = match.group(1).lower()
        if keyword in ("host", "match"):
            # An Include inside a block applies only to that block.
            return False
        if keyword == "include" and any(
            word == EXPORT_NAME or word.replace("\\", "/").endswith(f"/{EXPORT_NAME}")
            for word in _words(match.group(2))
        ):
            return True
    return False


def _words(text: str) -> list[str]:
    words = []
    for match in _WORD.finditer(text):
        quoted, plain = match.groups()
        if plain is not None and plain.startswith("#"):
            break
        words.append(quoted if quoted is not None else plain)
    return words


def add_include(config: Path) -> None:
    """Insert `INCLUDE_LINE` at the top of the SSH config, after a backup.

    Every other byte is kept, including a BOM and the file's line endings. A
    missing config is created with the line alone. A linked or read-only config
    is refused: replacing it would cut the link or override the user's choice.
    """
    by_hand = f"add this line at its top yourself: {INCLUDE_LINE}"
    if config.is_symlink():
        raise ExportError(f"{config.name} is a link; {by_hand}")
    if config.exists() and not os.access(config, os.W_OK):
        raise ExportError(f"{config.name} is read-only; {by_hand}")
    try:
        if not config.exists():
            config.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
            replace_atomically(config, f"{INCLUDE_LINE}\n".encode(), mode_from=None)
            if os.name == "posix":
                config.chmod(0o600)
            return
        original = config.read_bytes()
        replace_atomically(config.with_name(BACKUP_NAME), original, mode_from=None)
        newline = b"\r\n" if b"\r\n" in original else b"\n"
        bom = _BOM if original.startswith(_BOM) else b""
        updated = bom + INCLUDE_LINE.encode() + newline + original[len(bom) :]
        keep_mode = config if os.name == "posix" else None
        replace_atomically(config, updated, mode_from=keep_mode)
    except OSError as error:
        raise ExportError(
            f"Could not change {config.name}: {_reason(error)}."
        ) from None


def _reason(error: OSError) -> str:
    return (
        "permission denied" if isinstance(error, PermissionError) else "could not write"
    )
